"""Download item icons from the Don't Starve Wiki for the items in Data/wiki-items.json.

Run from the project folder:

    python Tools/fetch-item-images.py

For every item it asks the wiki's MediaWiki API for "File:<item name>.png", saves
the icon to wwwroot/images/items/ and records it in manifest.json, which the app
reads at startup (Services/ItemImages.cs). Items without an icon are simply left
out of the manifest and the app shows a placeholder for them.

Icons already on disk are not downloaded again, so the script can be re-run
after new items are added to the catalog.

The icons are game artwork (c) Klei Entertainment, taken from
https://dontstarve.wiki.gg and used here for a course project.
"""

import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://dontstarve.wiki.gg/api.php"
USER_AGENT = "Mozilla/5.0 (compatible; course-project-icon-fetcher)"
BATCH_SIZE = 50          # MediaWiki allows 50 titles per request
ICON_WIDTH = 128         # larger originals are scaled down by the wiki
PAUSE_SECONDS = 0.05     # be polite to the wiki

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "Data" / "wiki-items.json"
OUTPUT = ROOT / "wwwroot" / "images" / "items"
MANIFEST = OUTPUT / "manifest.json"


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def find_icon_urls(file_titles):
    """Return {requested title: icon url} for the titles that exist on the wiki."""
    found = {}
    for start in range(0, len(file_titles), BATCH_SIZE):
        batch = file_titles[start:start + BATCH_SIZE]
        query = urllib.parse.urlencode({
            "action": "query",
            "format": "json",
            "prop": "imageinfo",
            "iiprop": "url",
            "iiurlwidth": ICON_WIDTH,
            "titles": "|".join(batch),
        })
        data = json.loads(get(f"{API}?{query}"))["query"]

        # The wiki may rewrite a title (e.g. underscores to spaces); follow that back.
        requested_by_final = {title: title for title in batch}
        for change in data.get("normalized", []):
            requested_by_final[change["to"]] = change["from"]

        for page in data.get("pages", {}).values():
            info = page.get("imageinfo")
            requested = requested_by_final.get(page.get("title"))
            if info and requested:
                found[requested] = info[0].get("thumburl") or info[0]["url"]

        time.sleep(PAUSE_SECONDS)
        print(f"  looked up {min(start + BATCH_SIZE, len(file_titles))} / {len(file_titles)}", end="\r")
    print()
    return found


def file_name_for(item_name):
    slug = re.sub(r"[^a-z0-9]+", "-", item_name.lower()).strip("-")
    return f"{slug or 'item'}.png"


def main():
    names = [item["name"] for item in json.loads(CATALOG.read_text(encoding="utf-8"))["items"]]
    OUTPUT.mkdir(parents=True, exist_ok=True)

    print(f"Looking up icons for {len(names)} items...")
    title_for = {name: f"File:{name}.png" for name in names}
    urls = find_icon_urls(sorted(set(title_for.values())))

    # Second try for variants such as "Berries/DST": use the icon of the base item.
    base_title_for = {
        name: f"File:{name.split('/')[0]}.png"
        for name in names
        if "/" in name and title_for[name] not in urls
    }
    missing_bases = sorted(set(base_title_for.values()) - set(urls))
    if missing_bases:
        print(f"Looking up {len(missing_bases)} base items for variants...")
        urls.update(find_icon_urls(missing_bases))

    manifest = {}
    downloaded = 0
    for name in names:
        url = urls.get(title_for[name]) or urls.get(base_title_for.get(name, ""))
        if not url:
            continue

        file_name = file_name_for(name)
        target = OUTPUT / file_name
        if not target.exists():
            try:
                target.write_bytes(get(url))
            except OSError as error:
                print(f"  could not download {name}: {error}")
                continue
            downloaded += 1
            time.sleep(PAUSE_SECONDS)
            print(f"  downloaded {downloaded}", end="\r")
        manifest[name] = file_name
    print()

    MANIFEST.write_text(
        json.dumps({
            "source": "Don't Starve Wiki (https://dontstarve.wiki.gg)",
            "note": "Game artwork (c) Klei Entertainment. Generated by Tools/fetch-item-images.py.",
            "images": dict(sorted(manifest.items())),
        }, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")

    without = [name for name in names if name not in manifest]
    print(f"{len(manifest)} of {len(names)} items have an icon ({downloaded} newly downloaded).")
    print(f"{len(without)} items have no icon, for example: {', '.join(without[:8])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
